"""An index of every evaluation run and question bank, read from the files themselves.

    python -m eval.runs_index        # writes eval/results/INDEX.md

Each run's folder in eval/results/ keeps its manifest, answers, scores and PROV records; a
re-score sits beside the original as results.rescored.json and never replaces it. This
index only gathers what those files say, so it cannot drift from them: rerun it after a
run. Notes written by hand after a run (NOTE.md, NOTE.txt) are linked, not copied.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
BANKS = HERE / "questions"
OUT = RESULTS / "INDEX.md"


def _rate(s: dict[str, Any], key: str) -> str:
    r = s.get(key)
    if not isinstance(r, dict) or not r.get("n"):
        return ""
    return f"{r['k']}/{r['n']} ({100 * r['rate']:.1f}%)"


def _run_row(folder: Path) -> str:
    notes = [f"[{n.name}]({folder.name}/{n.name})" for n in sorted(folder.glob("NOTE*"))]
    if (folder / "audit").is_dir():
        notes.append(f"[audit]({folder.name}/audit/)")
    path = folder / "results.json"
    if not path.exists():
        return f"| {folder.name} | no results.json |  |  |  |  |  |  | {' '.join(notes)} |"
    report = json.loads(path.read_text(encoding="utf-8"))
    m, s = report.get("manifest", {}), report.get("summary", {})
    if "bank" in m:
        what = f"{m['bank_version']} {m['split']}"
        scope = f"phrasings {m.get('phrasings')} ×{m.get('repeats')}"
        if m.get("only"):
            scope += f", only {m['only']!r}"
        scorer = m.get("scorer") or "data-scorer/v1"
    else:
        what = "samples (Phase 1)"
        scope = f"×{m['repeats']}" if m.get("repeats") else ""
        scorer = ""
    correct = _rate(s, "in_scope_correct") or (
        f"{s['correct']}/{s['cases']}" if "cases" in s else ""
    )
    wrong = _rate(s, "accepted_but_wrong")
    rescored = folder / "results.rescored.json"
    if rescored.exists():
        r = json.loads(rescored.read_text(encoding="utf-8"))
        by = (r.get("rescored") or {}).get("scorer") or "current checks"
        notes.append(f"rescored ({by}): {_rate(r['summary'], 'in_scope_correct')}")
    cost = f"${s['estimated_usd']:.2f}" if s.get("estimated_usd") is not None else ""
    commit = (m.get("commit") or "")[:7]
    return (
        f"| {folder.name} | {what} | {scope} | {m.get('model', '')} | {scorer} | {correct}"
        f" | {wrong} | {cost} {commit} | {' '.join(notes)} |"
    )


def _bank_row(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    bank = json.loads(text)
    splits: dict[str, int] = {}
    for item in bank["items"]:
        splits[item["split"]] = splits.get(item["split"], 0) + 1
    sha = hashlib.sha256(text.encode()).hexdigest()[:16]
    counts = ", ".join(f"{k} {v}" for k, v in sorted(splits.items()))
    return f"| {path.name} | {bank['version']} | sha256:{sha} | {len(bank['items'])} | {counts} |"


def build() -> str:
    runs = sorted(p for p in RESULTS.iterdir() if p.is_dir())
    lines = [
        "# Evaluation runs and question banks",
        "",
        "Generated by `python -m eval.runs_index` from the files in this folder; do not edit.",
        "Each run's manifest (in its results.json) has the full settings: commit, prompt and",
        "bank hashes, scorer, model, price. The method and headline results are in",
        "docs/evaluation.md.",
        "",
        "In git: each run's results.json (every question, answer, verdict and score), notes and",
        "audit sheets. On this machine only (gitignored, about 4-5 MB per repeat): records/, the",
        "PROV record of every answer, and records/uploads-r*/, copies of data/ the run uploaded.",
        "",
        "## Question banks (eval/questions/)",
        "",
        "| File | Version | Hash | Items | Splits |",
        "|---|---|---|---|---|",
        *(_bank_row(p) for p in sorted(BANKS.glob("*.json"))),
        "",
        "## Runs (eval/results/)",
        "",
        "In-scope correct and accepted-but-wrong are as scored when the run was made.",
        "",
        "| Run | Bank and split | Questions | Model | Scorer | In-scope correct"
        " | Accepted but wrong | Cost, commit | Notes |",
        "|---|---|---|---|---|---|---|---|---|",
        *(_run_row(p) for p in runs),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"written {OUT}")


if __name__ == "__main__":
    main()
